/**
 * The player page for the live walkthrough take.
 *
 * Kept in its own module so index.html can be re-rendered from an existing scenes.json without
 * filming again. The recorder writes it after each take; tools/render-walkthrough-player.mjs
 * writes it on demand.
 */

/**
 * The optional browser player keeps the original picture and voice as separate source files.
 * The standalone MP4 produced by tools/export_walkthrough.py embeds its narration. Three things about that pairing are load-bearing:
 *
 *  - The recorder's webm carries no duration header, so Chrome reports Infinity/NaN until it is
 *    forced to read the last cluster. The page asks for a moment far past the end and returns.
 *  - Every visible length comes from the measured manifest, never from the media element.
 *  - Some browsers will not read media next to a page opened from the file system, so the page
 *    explains the one-command local server and reports what actually failed instead of sitting
 *    there looking like a black rectangle.
 */
export function player(manifest) {
  const data = JSON.stringify(manifest).replace(/</g, '\\u003c');
  const stamp = ms => {
    const seconds = Math.round(ms / 1000);
    return `${Math.floor(seconds / 60)}:${String(seconds % 60).padStart(2, '0')}`;
  };

  return [
    '<!doctype html>',
    '<html lang="en">',
    '<head>',
    '<meta charset="utf-8">',
    '<meta name="viewport" content="width=device-width, initial-scale=1">',
    '<title>NineCube.Digital — live system walkthrough</title>',
    '<style>',
    ':root { color-scheme: dark; --ink:#120e0a; --surface:#1b1510; --line:#3a2c1d; --amber:#ffab4d;',
    '  --text:#f3e7d8; --muted:#b9a68f; }',
    '* { box-sizing: border-box; }',
    'body { margin: 0; background: var(--ink); color: var(--text); font: 15px/1.55 system-ui, sans-serif; }',
    'header { display: flex; flex-wrap: wrap; gap: 12px; align-items: baseline; justify-content: space-between;',
    '  padding: 18px 24px; border-bottom: 1px solid var(--line); }',
    'h1 { margin: 0; font-size: 20px; } h1 span { color: var(--amber); }',
    'main { max-width: 1180px; margin: 0 auto; padding: 24px; display: grid; gap: 22px; }',
    '.stage { position: relative; }',
    'video { width: 100%; display: block; border: 1px solid var(--line); border-radius: 14px; background: #000;',
    '  box-shadow: 0 18px 48px rgba(0,0,0,.5); aspect-ratio: 1440 / 900; }',
    '.controls { display: flex; flex-wrap: wrap; gap: 12px; align-items: center; }',
    '#seek { flex: 1 1 220px; height: 8px; accent-color: var(--amber); }',
    '#now { margin: 0; color: var(--muted); font-size: 14px; min-height: 20px; }',
    '#warn { margin: 0; padding: 12px 14px; border-radius: 12px; background: #2b1410; border: 1px solid #7c3b2d;',
    '  color: #ffd9cd; font-size: 14px; }',
    '#warn code { color: #ffab4d; }',
    'button { font: inherit; padding: 9px 16px; border-radius: 999px; border: 1px solid var(--line);',
    '  background: var(--surface); color: var(--text); cursor: pointer; }',
    'button.primary { background: var(--amber); color: #1a1100; border-color: var(--amber); font-weight: 700; }',
    'button:disabled { opacity: .5; cursor: default; }',
    '.hint { color: var(--muted); }',
    'ol { list-style: none; margin: 0; padding: 0; display: grid; gap: 8px; }',
    'li { display: grid; grid-template-columns: 34px 1fr auto; gap: 12px; align-items: center;',
    '  padding: 10px 14px; border: 1px solid var(--line); border-radius: 12px; background: var(--surface); }',
    'li b { color: var(--amber); font-size: 14px; } li .when { color: var(--muted); font-variant-numeric: tabular-nums; }',
    'li button { padding: 6px 12px; } li.error { border-color: #e5484d; } li.error b { color: #ffb4b4; }',
    '.script { display: grid; gap: 14px; }',
    '.script p { margin: 4px 0 0; color: var(--muted); }',
    'footer { padding: 20px 24px 40px; color: var(--muted); border-top: 1px solid var(--line); }',
    'code { color: var(--amber); }',
    '</style>',
    '</head>',
    '<body>',
    '<header><h1><span>NineCube</span>.Digital — live system walkthrough</h1>',
    `<div class="hint">${stamp(manifest.totalMs)} recorded from the running application, with the voice track cut to the same timeline.</div></header>`,
    '<main>',
    '<p><a href="ninecube-walkthrough.mp4" download style="color:var(--amber);font-weight:700">Download the standalone MP4 with sound</a> · Open it in your desktop video player. No browser or local server is required for the MP4.</p>',
    // The recorder's webm carries no duration header, so the browser has nothing to scrub against.
    // The timeline is drawn from the measured manifest instead, which is exact.
    '<div class="stage">',
    `<video id="film" playsinline preload="auto" src="${manifest.video}"></video>`,
    '</div>',
    `<audio id="voice" preload="auto" src="${manifest.narration}"></audio>`,
    '<div class="controls">',
    '<button id="play" class="primary">Play with narration</button>',
    `<input id="seek" type="range" min="0" max="${manifest.totalMs}" step="100" value="0" aria-label="Seek the recording">`,
    `<span class="hint" id="clock">0:00 / ${stamp(manifest.totalMs)}</span>`,
    '<button id="mute">Voice on</button>',
    '</div>',
    '<p id="warn" hidden></p>',
    '<p id="now"></p>',
    '<nav aria-label="Scenes"><ol id="chapters"></ol></nav>',
    '<section class="script" aria-label="Narration script" id="script"></section>',
    '</main>',
    `<footer>Written by <code>web/scripts/record-walkthrough.mjs</code> on ${manifest.generatedAt.slice(0, 10)}.`,
    'The picture and the voice are two files: nothing on the machine that filmed them can mux them',
    'into one container, so this page runs them together. If the player below reports that the media',
    'could not be read, the browser is refusing files opened straight off the disk. Serve the folder',
    'instead — from the repository root, <code>node tools/serve-walkthrough.mjs</code> and then open',
    '<code>http://127.0.0.1:8089/</code>. Re-record with <code>node scripts/record-walkthrough.mjs</code>,',
    're-cut the voice with <code>python tools/narrate_walkthrough.py</code>, and re-render this page with',
    '<code>node tools/render-walkthrough-player.mjs</code>.</footer>',
    '<script type="application/json" id="manifest">' + data + '</script>',
    '<script>',
    'var m = JSON.parse(document.getElementById("manifest").textContent);',
    'var film = document.getElementById("film"), voice = document.getElementById("voice");',
    'var play = document.getElementById("play"), mute = document.getElementById("mute");',
    'var clock = document.getElementById("clock"), seek = document.getElementById("seek");',
    'var now = document.getElementById("now"), chapters = document.getElementById("chapters");',
    'var script = document.getElementById("script"), warn = document.getElementById("warn");',
    'var voiceBroken = false, shown = 0, probing = false;',
    'function at(ms) { var s = Math.round(ms / 1000); return Math.floor(s / 60) + ":" + ("0" + (s % 60)).slice(-2); }',
    'function note(message) { warn.textContent = message; warn.hidden = false; }',
    'function clearNote() { warn.hidden = true; }',
    'function broken() {',
    '  voiceBroken = true; mute.disabled = true;',
    `  note("The voice track (" + m.narration + ") cannot be read. Cut it with python tools/narrate_walkthrough.py; the picture still plays on its own.");`,
    '}',
    'function label(ms) {',
    '  var scene = m.scenes[0];',
    '  for (var i = 0; i < m.scenes.length; i++) { if (ms >= m.scenes[i].startMs) scene = m.scenes[i]; }',
    '  if (scene.scene === shown) return;',
    '  shown = scene.scene;',
    '  now.textContent = "Scene " + scene.scene + " of " + m.scenes.length + " · " + scene.title + " — " +',
    '    (scene.error ? "blocked: " + scene.error : scene.caption);',
    '}',
    'm.scenes.forEach(function (scene) {',
    '  var li = document.createElement("li");',
    '  if (scene.error) li.className = "error";',
    '  var n = document.createElement("b"); n.textContent = String(scene.scene);',
    '  var body = document.createElement("div");',
    '  var t = document.createElement("strong"); t.textContent = scene.title;',
    '  var c = document.createElement("p"); c.textContent = scene.error ? ("Blocked: " + scene.error) : scene.caption;',
    '  body.append(t, c);',
    '  var right = document.createElement("div");',
    '  var when = document.createElement("span"); when.className = "when"; when.textContent = at(scene.durationMs);',
    '  var go = document.createElement("button"); go.textContent = "Play";',
    '  go.onclick = function () { jump(scene.startMs + 250); start(); };',
    '  right.append(when, document.createTextNode(" "), go);',
    '  li.append(n, body, right); chapters.append(li);',
    '  var line = document.createElement("div");',
    '  var lt = document.createElement("strong"); lt.textContent = scene.scene + ". " + scene.title;',
    '  var ln = document.createElement("p"); ln.textContent = scene.narration;',
    '  line.append(lt, ln); script.append(line);',
    '});',
    'function jump(ms) { try { film.currentTime = ms / 1000; voice.currentTime = ms / 1000; } catch (e) { /* not readable yet */ } }',
    'function start() {',
    '  var picture = film.play();',
    '  if (picture && picture.catch) picture.catch(function (error) {',
    `    note("The browser refused the picture (" + error.name + "). The file " + m.video + " has to sit next to this page, and some browsers still refuse that from the file system: run node tools/serve-walkthrough.mjs and open http://127.0.0.1:8089/.");`,
    '  });',
    '  if (!voiceBroken) voice.play().catch(broken);',
    '}',
    'function toggle() { if (film.paused) { start(); play.textContent = "Pause"; } else { film.pause(); voice.pause(); play.textContent = "Play"; } }',
    'play.onclick = toggle;',
    'film.onclick = toggle;',
    'film.onplay = function () { if (!voiceBroken && voice.paused) voice.play().catch(broken); };',
    'film.onpause = function () { voice.pause(); play.textContent = "Play"; };',
    'film.onloadedmetadata = function () {',
    '  if (isFinite(film.duration) && film.duration > 1) { probing = false; clearNote(); return; }',
    '  probing = true;',
    '  // No duration header: Chrome only computes one once it has read to the end of the stream, so',
    '  // ask for a quarter of a megasecond and let the answer come back as a durationchange.',
    '  try { film.currentTime = 6e5; } catch (e) { probing = false; }',
    '};',
    'film.ondurationchange = function () {',
    '  if (!probing || !isFinite(film.duration) || film.duration < 1) return;',
    '  probing = false; clearNote();',
    '  try { film.currentTime = 0; } catch (e) {}',
    '};',
    `film.onerror = function () { note("The picture (" + m.video + ") could not be read from this folder. Keep it beside index.html, or serve the folder with node tools/serve-walkthrough.mjs."); };`,
    'film.onseeked = function () { if (probing) return; if (Math.abs(film.currentTime - voice.currentTime) > 0.34) jump(film.currentTime * 1000); };',
    'film.ontimeupdate = function () {',
    '  if (probing) return;',
    '  var ms = film.currentTime * 1000;',
    '  seek.value = String(Math.round(Math.min(ms, m.totalMs)));',
    '  clock.textContent = at(ms) + " / " + at(m.totalMs);',
    '  label(ms);',
    '  if (!film.paused && !voice.paused && Math.abs(film.currentTime - voice.currentTime) > 0.34) voice.currentTime = film.currentTime;',
    '};',
    'seek.oninput = function () { jump(Number(seek.value)); label(Number(seek.value)); };',
    'mute.onclick = function () { voice.muted = !voice.muted; mute.textContent = voice.muted ? "Voice off" : "Voice on"; };',
    'voice.onerror = broken;',
    'label(0);',
    '</script>',
    '</body>',
    '</html>',
    ''
  ].join('\n');
}
